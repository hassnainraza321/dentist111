            </li>
            <li>
                <i class="fa fa-check" aria-hidden="true"></i>
                <div>
                    <strong>To avoid damage: </strong>
                    Keep retainers away from pets, extreme heat, and potentially crushing objects like books or pockets.
                </div>
            </li>
            <li>
                <i class="fa fa-check" aria-hidden="true"></i>
                <div>
                    <strong>Stay Consistent: </strong>
                    Wear your retainers as instructed by your orthodontist to prevent teeth from shifting.
