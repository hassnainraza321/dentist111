<h2>Understand What Causes Discoloration</h2>
<p>
    It’s essential to understand what can stain your teeth. Teeth discolouration often occurs due to daily habits, dietary choices, and ageing. The enamel, the outermost layer of your teeth, can accumulate stains over time. Additionally, microscopic cracks in the enamel can trap pigments, leading to a dull appearance. Smoking and poor oral hygiene exacerbate the issue, making it harder to maintain whitened teeth. Recognizing these factors helps you take proactive measures to prevent stains from returning.
</p>
<p>
    <strong>Common Causes of Teeth Discoloration:</strong>
</p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Dietary Habits: </strong>
            Consuming dark-coloured foods and beverages such as coffee, tea, red wine, and berries can stain over time.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Smoking and Tobacco Use: </strong>
            Tar and nicotine from smoking are notorious for causing deep, persistent stains.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Poor Oral Hygiene: </strong>
            Inadequate brushing and flossing allow plaque and tartar to build up, trapping stains.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Ageing: </strong>
            As you age, the enamel on your teeth thins, making the yellowish dentin underneath more visible.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Certain Medications: </strong>
            Some antibiotics and medications can cause intrinsic teeth staining.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Trauma or Injury: </strong>
            Damage to a tooth can cause it to darken over time.
        </div>
    </li>
</ul>
<p class="pt-3">Understanding these causes, you can better protect your teeth from discolouration and maintain your smile.</p>
