<h2 class="pt-3">Causes of Gingivitis</h2>
<p>
    Understanding the causes of gingivitis is essential for prevention. Here are the key factors that contribute to this condition:
</p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Poor Oral Hygiene: </strong>
            Neglecting regular brushing and flossing causes plaque accumulation, which can result in gum inflammation.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Smoking and Tobacco Use: </strong>
            Tobacco products weaken the immune system, making it harder to fight off gum infections.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Hormonal Changes: </strong>
            Pregnancy, menstruation, and menopause can make gums more sensitive and prone to gingivitis.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Medications: </strong>
            Certain drugs, such as anticonvulsants and calcium channel blockers, can cause gum overgrowth, increasing the risk of gingivitis.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Chronic Illnesses: </strong>
            Conditions like diabetes, cancer, and HIV compromise the immune system, making it harder to maintain healthy gums.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Poor Nutrition: </strong>
            A diet deficient in vital vitamins and minerals, especially vitamin C, can weaken gum tissue.
        </div>
    </li>
</ul>
<p class="pt-3">
    Addressing these causes can significantly reduce your risk of developing gingivitis.
</p>
