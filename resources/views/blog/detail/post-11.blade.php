<h2 class="pt-3">Causes of Gum Disease</h2>
<p>
    Plaque is the main factor responsible for gum disease, a clingy layer of bacteria that forms on your teeth. When not removed through brushing and flossing, Plaque transforms into tartar, which can only be eliminated by a dentist. Here are some common risk factors:
</p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Poor oral hygiene: </strong>
            Irregular brushing and flossing allow Plaque to build up, creating a breeding ground for harmful bacteria.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Smoking or tobacco use: </strong> 
            Reduces gum tissue's ability to heal and fight infection, significantly increasing the risk of severe gum disease.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Genetics: </strong>
            Certain individuals may have a genetic tendency towards gum disease, making them more susceptible despite good oral hygiene.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Hormonal changes in women: </strong>
            Pregnancy, menopause, and menstrual cycles can increase gum sensitivity and the risk of inflammation.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Diabetes and other systemic diseases: </strong>
            These conditions weaken the immune system, impairing the body's ability to fight infections, including gum disease.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Medications that reduce saliva flow: </strong>
            Saliva helps wash away bacteria and debris. Reduced saliva increases the risk of plaque accumulation and gum disease.
        </div>
    </li>
</ul>
<p class="pt-3">Awareness of these risk factors can empower you to maintain your gum health proactively.</p>
<h2>Stages of Gum Disease</h2>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Healthy Gums: </strong>
            No signs of inflammation or disease. Gums are firm and pink and tightly hugged with the teeth to provide essential support.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Gingivitis: </strong>
            Mild gum inflammation without bone loss. This stage is reversible with improved oral care and professional cleanings. It is frequently overlooked because it doesn't cause pain.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Early Periodontitis: </strong>
            Slight bone loss occurs, and gum pockets form around teeth, allowing bacteria to accumulate. This stage marks the onset of irreversible damage.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Moderate Periodontitis: </strong>
            Increased bone and tissue damage leads to visible gum recession and potential tooth loosening. Professional treatment is critical to manage progression.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Advanced Periodontitis causes severe</strong>
            damage to gums and bone, leading to deep pockets, chronic infections, and tooth loss. Advanced treatments, including surgery, are often required at this stage.
        </div>
    </li>
</ul>
<h2 class="pt-3">How Is Gum Disease Treated?</h2>
<p>
    Effective treatment depends on the stage of gum disease. Your dentist will recommend the best course of action based on the severity of your condition. A combination of professional care and at-home oral hygiene practices is essential.
</p>
<p><strong>Non-Surgical Treatments</strong></p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Professional Cleaning: </strong>
            Removes Plaque and tartar through scaling and polishing. It is crucial for preserving oral health and preventing disease progression.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Scaling and Root Planing (Deep Cleaning): </strong>
            A deep cleaning beneath the gum line to eliminate tartar and bacteria. This helps smooth root surfaces to discourage bacterial growth and supports gum reattachment.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Antibiotics: </strong>
            These are used to treat localized gum infections or reduce bacterial load. These can be administered as oral medications, gels, or slow-release chips in gum pockets. Antibiotics are often combined with other treatments for maximum efficacy.
        </div>
    </li>
</ul>
<p class="pt-3"><strong>Surgical Treatments</strong></p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Flap Surgery (Pocket Reduction): </strong>
            Gums are lifted to remove tartar and smooth damaged bone. This reduces pocket depth and aids in healing. It's often recommended for advanced cases.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Bone Grafts: </strong>
            These procedures restore structural integrity by replacing lost bone with natural or synthetic material to support teeth and encourage regrowth.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Guided Tissue Regeneration: </strong>
            Stimulates bone and gum tissue growth to restore areas damaged by Periodontitis. This treatment helps rebuild supporting structures around teeth.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Soft Tissue Grafts: </strong>
            These replace damaged gum tissue with grafts from the roof of your mouth or other sources, improving appearance and reducing sensitivity. They also protect exposed tooth roots from decay.
        </div>
    </li>
</ul>
<p class="pt-3"><strong>Advanced Therapies</strong></p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Laser Therapy: </strong>
