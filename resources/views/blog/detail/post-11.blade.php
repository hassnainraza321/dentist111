    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Periodontal Maintenance: </strong>
            Regular follow-ups to prevent recurrence. These visits may include deep cleanings and close monitoring of gum health. Maintenance is key to the long-term management of gum disease.
        </div>
    </li>
</ul>
