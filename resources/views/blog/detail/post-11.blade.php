<h2>What Is Gum Disease?</h2>
<p>
    Gum disease is an infection of the tissues surrounding and supporting your teeth, primarily caused by plaque buildup. Left unchecked, this bacterial infection can lead to irreversible damage, including losing teeth and supporting bone. Despite being preventable, gum disease remains a leading cause of tooth loss globally. Understanding its progression and causes can help mitigate its impact.
</p>
<p>
    <strong>Types of Gum Disease</strong>
</p>
<ul class="checked-ul">
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Gingivitis: </strong>
            The initial phase of gum disease, characterized by red, swollen gums that may bleed when brushing. This stage is reversible with proper care and is often managed with routine dental cleanings and enhanced oral hygiene practices.
        </div>
    </li>
    <li>
        <i class="fa fa-check" aria-hidden="true"></i>
        <div>
            <strong>Periodontitis: </strong>
            A more advanced stage where gums pull away from the teeth, forming pockets that collect bacteria, leading to bone loss and potentially tooth loss. Periodontitis requires professional intervention for management, and in severe cases, surgical treatments may be necessary.
        </div>
    </li>
</ul>
